function loadHoeren1() {
  const container = document.getElementById("test-container-hoeren1");

  if (!container) return;

  container.innerHTML = "";

  const result = document.getElementById("resultHoeren1");

  if (result) {
    result.innerHTML = "";
  }

  hoerenTeil1.forEach((test, testIndex) => {
    const testBox = document.createElement("div");
    testBox.className = "hoeren1-test";

    const title = document.createElement("h2");
    title.textContent = test.title;

    testBox.appendChild(title);

    test.questions.forEach((q, questionIndex) => {
      const questionBox = document.createElement("div");
      questionBox.className = "hoeren1-question";

      const questionText = document.createElement("p");

      const number = document.createElement("strong");
      number.textContent = q.number + ". ";

      questionText.appendChild(number);
      questionText.appendChild(document.createTextNode(q.question));

      questionBox.appendChild(questionText);

      const optionsBox = document.createElement("div");
      optionsBox.className = "hoeren1-options";

      q.options.forEach((option, optionIndex) => {
        const label = document.createElement("label");
        label.className = "hoeren1-option";

        const input = document.createElement("input");

        input.type = "radio";
        input.name = `hoeren-${testIndex}-${questionIndex}`;

        let value;

        if (q.type === "truefalse") {
          value = optionIndex === 0 ? "R" : "F";
        } else {
          value = String.fromCharCode(97 + optionIndex);
        }

        input.value = value;

        const text = document.createElement("span");

        if (q.type === "choice") {
          text.textContent = `${String.fromCharCode(97 + optionIndex)}) ${option}`;
        } else {
          text.textContent = option;
        }

        label.appendChild(input);
        label.appendChild(text);

        // ==================================================
        // SOFORTIGE ANTWORTKONTROLLE
        // ==================================================

        input.addEventListener("change", function () {
          const allOptions = questionBox.querySelectorAll(".hoeren1-option");

          // Alte Markierungen entfernen
          allOptions.forEach((item) => {
            item.classList.remove("correct", "wrong");
          });

          // Richtige Antwort
          if (input.value === q.correct) {
            label.classList.add("correct");
          }

          // Falsche Antwort
          else {
            label.classList.add("wrong");

            // Richtige Antwort anzeigen
            allOptions.forEach((item) => {
              const itemInput = item.querySelector("input");

              if (itemInput && itemInput.value === q.correct) {
                item.classList.add("correct");
              }
            });
          }
        });

        optionsBox.appendChild(label);
      });

      questionBox.appendChild(optionsBox);
      testBox.appendChild(questionBox);
    });

    container.appendChild(testBox);
  });
}

// ======================================================
// HÖREN TEIL 1 AUSWERTEN
// ======================================================

function checkAllHoeren1() {
  let total = 0;
  let correct = 0;

  hoerenTeil1.forEach((test, testIndex) => {
    test.questions.forEach((q, questionIndex) => {
      total++;

      const selected = document.querySelector(
        `input[name="hoeren-${testIndex}-${questionIndex}"]:checked`,
      );

      if (selected && selected.value === q.correct) {
        correct++;
      }
    });
  });

  const percentage = total > 0 ? Math.round((correct / total) * 100) : 0;

  const result = document.getElementById("resultHoeren1");

  if (!result) return;

  result.innerHTML = `
    <div class="final-result">
      <h2>Ergebnis</h2>

      <p>
        Sie haben
        <strong>${correct}</strong>
        von
        <strong>${total}</strong>
        Fragen richtig beantwortet.
      </p>

      <p>
        Ergebnis:
        <strong>${percentage}%</strong>
      </p>
    </div>
  `;

  result.scrollIntoView({
    behavior: "smooth",
    block: "center",
  });
}
