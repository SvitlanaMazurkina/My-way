// HÖREN TEIL 2 LADEN
// ======================================================

function loadHoeren2() {
  const container = document.getElementById("test-container-hoeren2");

  if (!container) {
    return;
  }

  container.innerHTML = "";

  const result = document.getElementById("resultHoeren2");

  if (result) {
    result.innerHTML = "";
  }

  if (typeof hoerenTeil2 === "undefined" || !Array.isArray(hoerenTeil2)) {
    container.innerHTML = `
      <div class="error-message">
        Die Daten für Hören Teil 2 konnten nicht geladen werden.
      </div>
    `;

    return;
  }

  hoerenTeil2.forEach((test, testIndex) => {
    const testBox = document.createElement("div");

    testBox.className = "hoeren2-test";

    // ==================================================
    // TITEL
    // ==================================================

    const title = document.createElement("h2");

    title.textContent = test.title;

    testBox.appendChild(title);

    // ==================================================
    // ANTWORTMÖGLICHKEITEN
    // ==================================================

    const answersTitle = document.createElement("h3");

    answersTitle.textContent = "Antwortmöglichkeiten";

    testBox.appendChild(answersTitle);

    const answersBox = document.createElement("div");

    answersBox.className = "hoeren2-answers";

    test.options.forEach((option, optionIndex) => {
      const answerBox = document.createElement("div");

      answerBox.className = "hoeren2-answer";

      const letter = document.createElement("strong");

      letter.className = "hoeren2-answer-letter";

      letter.textContent = `${String.fromCharCode(97 + optionIndex)})`;

      const text = document.createElement("span");

      text.textContent = option;

      answerBox.appendChild(letter);
      answerBox.appendChild(text);

      answersBox.appendChild(answerBox);
    });

    testBox.appendChild(answersBox);

    // ==================================================
    // FRAGEN
    // ==================================================

    const questionsTitle = document.createElement("h3");

    questionsTitle.textContent = "Gespräche";

    testBox.appendChild(questionsTitle);

    const questionsBox = document.createElement("div");

    questionsBox.className = "hoeren2-questions";

    test.questions.forEach((question, questionIndex) => {
      const questionBox = document.createElement("div");

      questionBox.className = "hoeren2-question";

      // ------------------------------------------------
      // FRAGE
      // ------------------------------------------------

      const questionTitle = document.createElement("p");

      questionTitle.className = "hoeren2-question-title";

      const number = document.createElement("strong");

      number.textContent = `${question.number}. `;

      questionTitle.appendChild(number);

      questionTitle.appendChild(
        document.createTextNode("Welche Antwort passt?"),
      );

      questionBox.appendChild(questionTitle);

      // ------------------------------------------------
      // DIALOG
      // ------------------------------------------------

      const dialogue = document.createElement("div");

      dialogue.className = "hoeren2-dialogue";

      dialogue.style.whiteSpace = "pre-line";

      dialogue.textContent = question.dialogue.trim();

      questionBox.appendChild(dialogue);

      // ------------------------------------------------
      // ANTWORTEN
      // ------------------------------------------------

      const optionsBox = document.createElement("div");

      optionsBox.className = "hoeren2-options";

      const letters = ["a", "b", "c", "d", "e", "f"];

      letters.forEach((letter) => {
        const label = document.createElement("label");

        label.className = "hoeren2-option";

        const input = document.createElement("input");

        input.type = "radio";

        input.name = `hoeren2-${testIndex}-${questionIndex}`;

        input.value = letter;

        const letterSpan = document.createElement("span");

        letterSpan.className = "hoeren2-option-letter";

        letterSpan.textContent = letter;

        label.appendChild(input);
        label.appendChild(letterSpan);

        input.addEventListener("change", function () {
          checkHoeren2Answer(input, questionBox, question.correct);
        });

        optionsBox.appendChild(label);
      });

      questionBox.appendChild(optionsBox);

      questionsBox.appendChild(questionBox);
    });

    testBox.appendChild(questionsBox);

    container.appendChild(testBox);
  });
}

// ======================================================
// SOFORTIGE ANTWORTKONTROLLE
// ======================================================

function checkHoeren2Answer(input, questionBox, correctAnswer) {
  const options = questionBox.querySelectorAll(".hoeren2-option");

  options.forEach((option) => {
    option.classList.remove("correct", "wrong");
  });

  const selectedLabel = input.closest(".hoeren2-option");

  if (!selectedLabel) {
    return;
  }

  const selected = input.value.toLowerCase();

  const correct = String(correctAnswer).toLowerCase();

  if (selected === correct) {
    selectedLabel.classList.add("correct");
  } else {
    selectedLabel.classList.add("wrong");

    options.forEach((option) => {
      const optionInput = option.querySelector("input");

      if (optionInput && optionInput.value.toLowerCase() === correct) {
        option.classList.add("correct");
      }
    });
  }
}

// ======================================================
// HÖREN TEIL 2 AUSWERTEN
// ======================================================

function checkAllHoeren2() {
  let total = 0;
  let correct = 0;

  if (typeof hoerenTeil2 === "undefined" || !Array.isArray(hoerenTeil2)) {
    return;
  }

  hoerenTeil2.forEach((test, testIndex) => {
    if (!Array.isArray(test.questions)) {
      return;
    }

    test.questions.forEach((question, questionIndex) => {
      total++;

      const selected = document.querySelector(
        `input[name="hoeren2-${testIndex}-${questionIndex}"]:checked`,
      );

      if (
        selected &&
        selected.value.toLowerCase() === String(question.correct).toLowerCase()
      ) {
        correct++;
      }
    });
  });

  const percentage = total > 0 ? Math.round((correct / total) * 100) : 0;

  const result = document.getElementById("resultHoeren2");

  if (!result) {
    return;
  }

  result.innerHTML = `
    <div class="final-result">
      <h2>Ergebnis</h2>

      <p>
        Sie haben
        <strong>${correct}</strong>
        von
        <strong>${total}</strong>
        Fragen richtig beantwortet.
      </p>

      <p>
        Ergebnis:
        <strong>${percentage}%</strong>
      </p>
    </div>
  `;

  result.scrollIntoView({
    behavior: "smooth",
    block: "center",
  });
}
